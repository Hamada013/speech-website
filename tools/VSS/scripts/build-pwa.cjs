// One installable release for all VSS activities. Media remains opt-in.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..'),MODULES=['voc','senb','taffaha'];
const sha=(body,encoding='hex')=>crypto.createHash('sha256').update(body).digest(encoding);
function walk(directory){
 return fs.readdirSync(path.join(ROOT,directory),{withFileTypes:true}).flatMap(entry=>{
  if(['node_modules','tests','scripts'].includes(entry.name))return [];
  const file=directory+'/'+entry.name;
  return entry.isDirectory()?walk(file):[file];
 });
}
function createRelease(){
 const media=[];
 const add=(module,file)=>{const body=fs.readFileSync(path.join(ROOT,module,file));media.push({module,url:module+'/'+file,bytes:body.length,revision:sha(body)});};
 for(let category=1;category<=40;category++)for(const [kind,ext]of [['images','webp'],['sounds','m4a']]){
  for(const name of fs.readdirSync(path.join(ROOT,'voc',kind,String(category))).filter(name=>new RegExp(`^\\d+\\.${ext}$`).test(name)).sort())add('voc',`${kind}/${category}/${name}`);
 }
 const senbFiles=[...walk('senb/images'),...walk('senb/sounds')].filter(file=>/\.(webp|png|m4a)$/.test(file)).sort();
 for(const file of senbFiles)add('senb',file.slice('senb/'.length));
 const used=new Set(),{words}=JSON.parse(fs.readFileSync(path.join(ROOT,'taffaha/assets/words.json')));
 for(const word of words)for(const asset of [word.image,word.audio,...word.syllableAudio]){
  if(asset.library!=='taffaha'||!/^assets\/(images|sounds)\//.test(asset.path)||asset.path.split('/').includes('..'))throw Error('Invalid Taffaha media: '+asset.path);
  if(fs.existsSync(path.join(ROOT,'taffaha',asset.path)))used.add(asset.path);
  else if(asset===word.image||asset===word.audio)throw Error('Missing media: '+asset.path);
 }
 for(const file of [...used].sort())add('taffaha',file);
 media.sort((a,b)=>a.url.localeCompare(b.url));
 const files=MODULES.flatMap(module=>walk(module).filter(file=>{
  const local=file.slice(module.length+1);
  if(/^(images|sounds)\//.test(local))return module==='voc'&&(/^(images\/41\/|images\/(logo\.webp|placeholder\.svg)$)/.test(local));
  if(/^assets\/(images|sounds)\//.test(local))return false;
  return /\.(html|css|js|svg|json|png|webp|woff2|txt)$/.test(file)&&!['package.json','package-lock.json','sw.js','assets/pwa-release.js','manifest.json'].includes(local);
 }));
 const shell=[...new Set(['index.html','manifest.webmanifest',...walk('icons'),...walk('assets').filter(file=>file!=='assets/pwa-release.js'),...files])].sort();
 const integrity=Object.fromEntries(shell.map(file=>[file,'sha256-'+sha(fs.readFileSync(path.join(ROOT,file)),'base64')]));
 const version=sha(JSON.stringify({integrity,media,worker:sha(fs.readFileSync(path.join(ROOT,'sw.js')))})).slice(0,20);
 return {version,shell,integrity,media};
}
function build({check=false}={}){
 if(!check)require('../voc/scripts/build-game-data.cjs');
 fs.mkdirSync(path.join(ROOT,'icons'),{recursive:true});
 for(const file of ['icon-192.png','icon-512.png','maskable-512.png','apple-touch-icon.png']){
  const source=fs.readFileSync(path.join(ROOT,'voc/icons',file)),target=path.join(ROOT,'icons',file);
  if(check){if(!source.equals(fs.readFileSync(target)))throw Error('VSS must use VOC icons: '+file);}else fs.writeFileSync(target,source);
 }
 // Retained for the sentence media model and tooling; VSS downloads use the unified inventory.
 const assets=[...walk('senb/images'),...walk('senb/sounds')].filter(file=>/\.(webp|png|m4a)$/.test(file)).sort().map(file=>{
  const body=fs.readFileSync(path.join(ROOT,file));return {url:file.slice(5),bytes:body.length,revision:sha(body)};
 });
 const catalog=JSON.stringify({version:sha(JSON.stringify(assets)).slice(0,20),totalBytes:assets.reduce((sum,a)=>sum+a.bytes,0),assets});
 const catalogPath=path.join(ROOT,'senb/assets/offline-assets.json');
 if(check){if(fs.readFileSync(catalogPath,'utf8')!==catalog)throw Error('Sentence media catalog is stale');}else fs.writeFileSync(catalogPath,catalog);
 const release=createRelease(),output='// Generated by scripts/build-pwa.cjs.\nself.VSS_RELEASE='+JSON.stringify(release)+';\n',target=path.join(ROOT,'assets/pwa-release.js');
 if(check){if(fs.readFileSync(target,'utf8')!==output)throw Error('VSS release is stale; run npm run build --prefix tools/VSS');}else fs.writeFileSync(target,output);
 console.log(`VSS ${release.version}: ${release.shell.length} shell files; ${release.media.length} media files (${(release.media.reduce((sum,a)=>sum+a.bytes,0)/1e6).toFixed(1)} MB).`);
 return release;
}
if(require.main===module)build({check:process.argv.includes('--check')});
module.exports={build,createRelease};
