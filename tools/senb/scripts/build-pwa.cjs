// Run after changing media or app files; committed output needs no server build.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
function walk(directory) {
    return fs.readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap(entry => {
        const relative = `${directory}/${entry.name}`;
        return entry.isDirectory() ? walk(relative) : [relative];
    });
}
const media = [...walk('images'), ...walk('sounds')].filter(file => /\.(webp|png|m4a)$/.test(file)).sort();
const assets = media.map(url => {
    const body = fs.readFileSync(path.join(root, url));
    return { url, bytes: body.length, revision: hash(body) };
});
const catalog = { version: hash(JSON.stringify(assets)).slice(0, 20), totalBytes: assets.reduce((sum, entry) => sum + entry.bytes, 0), assets };
fs.writeFileSync(path.join(root, 'assets/offline-assets.json'), JSON.stringify(catalog));
const shell = ['index.html', 'manifest.webmanifest', ...walk('assets').filter(file => /\.(js|css|svg|json|png|webp)$/.test(file) && !file.endsWith('/pwa-release.js'))].sort();
const integrity = Object.fromEntries(shell.map(file => [file, `sha256-${crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('base64')}`]));
const version = hash(JSON.stringify([...shell, 'sw.js'].map(file => [file, hash(fs.readFileSync(path.join(root, file)))]))).slice(0, 20);
fs.writeFileSync(path.join(root, 'assets/pwa-release.js'), `// Generated by scripts/build-pwa.cjs; update with npm run build:pwa.\nself.SENB_RELEASE = ${JSON.stringify({ version, shell, integrity })};\n`);
console.log(`PWA release ${version}: ${assets.length} media files, ${(catalog.totalBytes / 1e6).toFixed(1)} MB; ${shell.length} shell files.`);
