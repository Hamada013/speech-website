// One label source for all four games. Keep numeric IDs stable around missing
// files; never show missing source images as indistinguishable quiz choices.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const start = source.indexOf('const RAW_CATEGORIES =');
const end = source.indexOf('const app =', start);
if (start < 0 || end < 0) throw new Error('Vocabulary labels not found');
const categories = vm.runInNewContext(`${source.slice(start, end)}; JSON.parse(JSON.stringify(CATEGORIES));`, {}, { timeout: 1000 });
const missing = [];
for (const category of categories) {
    category.items = category.items.filter(item => {
        const absent = [item.image, item.audio].filter(url => !fs.existsSync(path.join(root, url)));
        if (absent.length) { missing.push({ key: `${category.id}_${item.id}`, name: item.name, absent }); return false; }
        item.key = `${category.id}_${item.id}`;
        item.imageHash = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, item.image))).digest('hex').slice(0, 16);
        return true;
    });
}
const version = crypto.createHash('sha256').update(JSON.stringify(categories)).digest('hex').slice(0, 20);
fs.writeFileSync(path.join(root, 'assets/game-data.js'), `// Generated by scripts/build-game-data.cjs.\nwindow.VOC_GAME_DATA = ${JSON.stringify({ version, categories, missing })};\n`);
console.log(`Game bank: ${categories.reduce((n, c) => n + c.items.length, 0)} usable words; ${missing.length} missing-media entries excluded.`);
