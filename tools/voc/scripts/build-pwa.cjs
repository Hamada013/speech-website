// Run after editing app files or adding/removing media. Deploy the generated
// output directly on static hosting. No assumptions about folder lengths.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
// Direct invocations must keep the playable bank in sync with home-page words
// and converted media before calculating shell integrity hashes.
require('./build-game-data.cjs');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
function walk(dir) {
    return fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap(entry => {
        const url = `${dir}/${entry.name}`;
        return entry.isDirectory() ? walk(url) : [url];
    });
}
const groups = Array.from({ length: 40 }, (_, index) => {
    const folder = index + 1;
    const entries = (dir, ext) => fs.readdirSync(path.join(root, dir, String(folder)))
        .filter(name => new RegExp(`^\\d+\\.${ext}$`).test(name))
        .map(name => `${dir}/${folder}/${name}`);
    return [...entries('images', 'webp'), ...entries('sounds', 'm4a')]
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
});
const media = groups.map(files => files.map(url => {
    const body = fs.readFileSync(path.join(root, url));
    return { url, bytes: body.length, revision: hash(body) };
}));
const shell = ['index.html', 'games.html', 'matching.html', 'memory.html', 'rapid.html', 'test.html', 'report.html',
    'manifest.json', 'images/logo.webp', 'images/placeholder.svg', ...walk('icons'),
    ...walk('assets').filter(file => /\.(css|js|woff2|txt|webp)$/.test(file) && file !== 'assets/pwa-release.js')].sort();
const integrity = Object.fromEntries(shell.map(url => [url,
    `sha256-${crypto.createHash('sha256').update(fs.readFileSync(path.join(root, url))).digest('base64')}`]));
const version = hash(JSON.stringify({ integrity, media, worker: hash(fs.readFileSync(path.join(root, 'sw.js'))) })).slice(0, 20);
fs.writeFileSync(path.join(root, 'assets/pwa-release.js'),
    `// Generated by scripts/build-pwa.cjs. Do not edit.\nself.VOC_RELEASE = ${JSON.stringify({ version, shell, integrity, media })};\n`);
const all = media.flat();
console.log(`VOC release ${version}: ${all.length} media assets, ${(all.reduce((sum, a) => sum + a.bytes, 0) / 1e6).toFixed(1)} MB, ${shell.length} shell assets.`);
