// Run after changing any shipped file. Hashes make releases atomic and repeatable.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const shell = [
  'index.html', 'manifest.webmanifest', 'assets/app.js', 'assets/vendor.js',
  'assets/practice.js', 'assets/recording.js', 'assets/dialog.js', 'assets/pwa.js',
  'assets/index-B-ZKx10f.css', 'assets/responsive.css', 'assets/icons/icon.svg',
  'assets/icons/icon-192.png', 'assets/icons/icon-512.png',
  'assets/icons/icon-maskable-512.png', 'assets/icons/apple-touch-icon.png'
];
const integrity = Object.fromEntries(shell.map(file => [file, 'sha256-' + crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('base64')]));
const version = crypto.createHash('sha256').update(JSON.stringify(integrity)).update(fs.readFileSync(path.join(root, 'sw.js'))).digest('hex').slice(0, 16);
const release = '/* Generated by scripts/build-pwa.cjs. */\nself.FLUENCY_RELEASE = ' + JSON.stringify({ version, shell, integrity }, null, 2) + ';\n';
const target = path.join(root, 'assets/pwa-release.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== release) { console.error('PWA release is stale. Run node scripts/build-pwa.cjs.'); process.exitCode = 1; }
  else console.log('PASS PWA release matches every shipped file.');
} else { fs.writeFileSync(target, release); console.log(`Built offline release ${version}: ${shell.length} files`); }
